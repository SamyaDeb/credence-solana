// Copies the program's IDL from `anchor build` (target/idl) into the SDK and writes its hash: the SDK embeds both and
// refuses a program whose IDL differs (assertIdl). Fails if the program was never built.
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
const src = new URL('../../../target/idl/credence_core.json', import.meta.url);
if (!existsSync(src)) {
  console.error('target/idl/credence_core.json is missing: run `anchor build --arch v0` at the repo root');
  process.exit(1);
}
copyFileSync(src, new URL('../src/idl.json', import.meta.url));
// The hash is over the parsed document re-serialised with sorted keys, so formatting never changes it.
const sort = (v) => (Array.isArray(v) ? v.map(sort) : v && typeof v === 'object' ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, sort(v[k])])) : v);
const hash = createHash('sha256').update(JSON.stringify(sort(JSON.parse(readFileSync(src, 'utf8'))))).digest('hex');
writeFileSync(new URL('../src/idl-hash.ts', import.meta.url), `// Generated by scripts/sync-idl.mjs. Do not edit.\nexport const IDL_HASH = '${hash}';\n`);
console.log(`sdk idl synced, sha256 ${hash.slice(0, 16)}…`);
